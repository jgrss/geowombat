def _to_source(lines):
    text = "\n".join(lines)
    parts = text.split("\n")
    # Jupyter stores source as a list where every line except the last
    # has a trailing newline.
    out = []
    for i, p in enumerate(parts):
        if i < len(parts) - 1:
            out.append(p + "\n")
        else:
            out.append(p)
    return out



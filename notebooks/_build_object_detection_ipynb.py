    "   pixels across after tiling. For dense small objects, shrink",
    "   the tile (256–416 px) or use higher overlap so each object",
    "   gets seen in at least one un-cropped tile.",
    "",
    "7. **Sweep the confidence threshold *after* training.** Don't pick",
